func TestRender(t *testing.T) {
	spec, errs := appspec.Check([]byte(`name: moimroom
services:
  - name: web
    port: 8080
    healthCheck: /healthz
    public: true
    env: {LOG_LEVEL: info, MODE: "0755", "Y": "yes"}
  - name: worker
    path: worker
    port: 9000
    replicas: 2
resources:
  - {name: db, type: postgres}
  - {name: photos, type: s3}
`))
	if len(errs) > 0 {
		t.Fatal(errs)
	}
	f := File{App: "moimroom", Env: "eks", Commit: "9fceb02d0ae598e95dc970b74767f19372d61af8", Deployment: "dep_3f9c1a0b2d4e", Spec: *spec,
		Images: map[string]string{"web": "r/hopcharlie/apps/moimroom/web@sha256:aa", "worker": "r/hopcharlie/apps/moimroom/worker@sha256:bb"}}
	got, err := Render(f)
	if err != nil {
		t.Fatal(err)
	}
	want := `# Generated by the HopCharlie platform. Do not edit.
app: "moimroom"
env: "eks"
namespace: "moimroom"
commit: "9fceb02d0ae598e95dc970b74767f19372d61af8"
deployment: "dep_3f9c1a0b2d4e"
values:
  app: "moimroom"
  services:
    - name: "web"
      image: "r/hopcharlie/apps/moimroom/web@sha256:aa"
      port: 8080
      healthCheck: "/healthz"
      public: true
      replicas: 1
      env:
        "LOG_LEVEL": "info"
        "MODE": "0755"
        "Y": "yes"
    - name: "worker"
      image: "r/hopcharlie/apps/moimroom/worker@sha256:bb"
      port: 9000
      public: false
      replicas: 2
  resources:
    - name: "db"
      type: "postgres"
    - name: "photos"
      type: "s3"
`
	if string(got) != want {
		t.Fatalf("got:\n%s\nwant:\n%s", got, want)
	}
	again, _ := Render(f)
	if string(again) != string(got) {
		t.Fatal("rendering is not stable")
	}

	// Every reader sees the strings as strings, YAML 1.1 ones included.
	var v struct {
		Values struct {
			Services []struct {
				Env map[string]any `json:"env"`
			} `json:"services"`
		} `json:"values"`
	}
	if err := yaml.Unmarshal(got, &v); err != nil {
		t.Fatal(err)
	}
	if env := v.Values.Services[0].Env; env["MODE"] != "0755" || env["Y"] != "yes" {
		t.Fatalf("env read back as %#v", env)
	}

	f.Spec.Resources = nil
	got, _ = Render(f)
	if !strings.HasSuffix(string(got), "  resources: []\n") {
		t.Fatalf("no resources:\n%s", got)
	}
	delete(f.Images, "worker")
	if _, err := Render(f); err == nil {
		t.Fatal("rendered a service without an image")
	}
}

func TestBackends(t *testing.T) {
	svc := appspec.Service{Name: "web", Port: 8080}
	u, _ := TemplateBackends{Template: "http://{app}-{service}.{app}.svc.cluster.local:{port}/{env}"}.URL(context.Background(), "shop", "eks", svc)
	if u != "http://shop-web.shop.svc.cluster.local:8080/eks" {
		t.Fatal(u)
	}

	kube := kubefake.NewClientset(
		&corev1.Service{
			ObjectMeta: metav1.ObjectMeta{Name: "shop-web", Namespace: "shop"},
			Spec:       corev1.ServiceSpec{Ports: []corev1.ServicePort{{Name: "metrics", Port: 9100}, {Name: "http", Port: 80, TargetPort: intstr.FromInt32(8080)}}},
			Status:     corev1.ServiceStatus{LoadBalancer: corev1.LoadBalancerStatus{Ingress: []corev1.LoadBalancerIngress{{Hostname: "abc.elb.amazonaws.com"}}}},
		},
		&corev1.Service{
			ObjectMeta: metav1.ObjectMeta{Name: "cart-web", Namespace: "cart"},
			Spec:       corev1.ServiceSpec{Ports: []corev1.ServicePort{{Port: 8080}}},
			Status:     corev1.ServiceStatus{LoadBalancer: corev1.LoadBalancerStatus{Ingress: []corev1.LoadBalancerIngress{{IP: "203.0.113.7"}}}},
		},
		&corev1.Service{
			ObjectMeta: metav1.ObjectMeta{Name: "new-web", Namespace: "new"},
			Spec:       corev1.ServiceSpec{Ports: []corev1.ServicePort{{Port: 8080}}},
		},
	)
	calls := 0
	b := &ServiceBackends{Kube: func(env string) (kubernetes.Interface, error) { calls++; return kube, nil }}
	ctx := context.Background()
	if u, err := b.URL(ctx, "shop", "eks", svc); err != nil || u != "http://abc.elb.amazonaws.com" {
		t.Errorf("hostname: %q %v", u, err)
	}
	if u, err := b.URL(ctx, "cart", "eks", svc); err != nil || u != "http://203.0.113.7:8080" {
		t.Errorf("ip: %q %v", u, err)
	}
	if _, err := b.URL(ctx, "new", "eks", svc); err == nil || !strings.Contains(err.Error(), "no load balancer address yet") {
		t.Errorf("pending: %v", err)
	}
	if _, err := b.URL(ctx, "gone", "eks", svc); err == nil {
		t.Error("missing Service accepted")
	}
	if calls != 1 {
		t.Errorf("built the client %d times", calls)
	}
}
